/**
 * Generates db/seed.sql from server/data/seed.js so the MySQL fixtures and the
 * in-memory fixtures can never drift apart.
 *
 *   node scripts/gen-seed-sql.js
 */

const fs = require('fs');
const path = require('path');
const seed = require('../server/data/seed');

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? 'NULL' : String(v));

const lines = [];
lines.push('-- ============================================================');
lines.push('-- NearStock — seed data  (GENERATED by scripts/gen-seed-sql.js)');
lines.push('-- Run after db/schema.sql:  mysql -u root -p nearstock < db/seed.sql');
lines.push('-- ============================================================');
lines.push('');
lines.push('USE nearstock;');
lines.push('SET FOREIGN_KEY_CHECKS = 0;');
lines.push('TRUNCATE TABLE billing_sync;');
lines.push('TRUNCATE TABLE request_queue;');
lines.push('TRUNCATE TABLE inventory;');
lines.push('TRUNCATE TABLE products;');
lines.push('TRUNCATE TABLE stores;');
lines.push('TRUNCATE TABLE users;');
lines.push('SET FOREIGN_KEY_CHECKS = 1;');
lines.push('');

lines.push('INSERT INTO users (user_id, name, email, phone, role, latitude, longitude) VALUES');
lines.push(seed.users.map((u) =>
  `  (${u.user_id}, ${q(u.name)}, ${q(u.email)}, ${q(u.phone)}, ${q(u.role)}, ${n(u.latitude)}, ${n(u.longitude)})`
).join(',\n') + ';');
lines.push('');

lines.push('INSERT INTO stores (store_id, owner_id, name, category, address, city, phone, latitude, longitude, opens_at, closes_at, rating) VALUES');
lines.push(seed.stores.map((s) =>
  `  (${s.store_id}, ${n(s.owner_id)}, ${q(s.name)}, ${q(s.category)}, ${q(s.address)}, ${q(s.city)}, ${q(s.phone)}, ${n(s.latitude)}, ${n(s.longitude)}, ${q(s.opens_at + ':00')}, ${q(s.closes_at + ':00')}, ${n(s.rating)})`
).join(',\n') + ';');
lines.push('');

lines.push('INSERT INTO products (product_id, name, brand, category, unit, base_price, barcode, image_emoji) VALUES');
lines.push(seed.products.map((p) =>
  `  (${p.product_id}, ${q(p.name)}, ${q(p.brand)}, ${q(p.category)}, ${q(p.unit)}, ${n(p.base_price)}, ${q(p.barcode)}, ${q(p.image_emoji)})`
).join(',\n') + ';');
lines.push('');

lines.push('INSERT INTO inventory (store_id, product_id, quantity, price) VALUES');
lines.push(seed.inventoryTuples.map(([s, p, qty, price]) =>
  `  (${s}, ${p}, ${qty}, ${price})`
).join(',\n') + ';');
lines.push('');

lines.push('INSERT INTO request_queue (store_id, product_id, customer_name, customer_phone, quantity, note, position, status, processed_at) VALUES');
lines.push(seed.queueSeed.map((r, i) =>
  `  (${r.store_id}, ${r.product_id}, ${q(r.customer_name)}, ${q(r.customer_phone)}, ${r.quantity}, ${q(r.note || '')}, ${i + 1}, ${q(r.status)}, ${r.status === 'waiting' ? 'NULL' : 'NOW()'})`
).join(',\n') + ';');
lines.push('');
lines.push('SELECT');
lines.push("  (SELECT COUNT(*) FROM stores)        AS stores,");
lines.push("  (SELECT COUNT(*) FROM products)      AS products,");
lines.push("  (SELECT COUNT(*) FROM inventory)     AS inventory_lines,");
lines.push("  (SELECT COUNT(*) FROM request_queue) AS queued_requests;");
lines.push('');

const out = path.join(__dirname, '..', 'db', 'seed.sql');
fs.writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out} — ${seed.stores.length} stores, ${seed.products.length} products, ${seed.inventoryTuples.length} inventory lines.`);
